import AppKit
import Foundation
import UniformTypeIdentifiers

@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published var isPaused = false
    var onCapture: ((ClipItem, NSImage?, Data?) -> Void)?
    var onSound: (() -> Void)?
    /// Delivered when a remote `<img>` finishes downloading after the clip was
    /// already captured. The card is updated in place.
    var onRemoteImage: ((UUID, NSImage) -> Void)?
    /// Apps whose copies are never recorded. Empty by default — the user decides
    /// what to skip, so nothing is pre-excluded.
    @Published var ignoredBundleIDs: Set<String> = []
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChangeCount = 0
    private var pendingCount: Int?
    private var ignoredCounts: Set<Int> = []
    /// Content a source app itself marked as secret (the cross-app convention
    /// from nspasteboard.org). No app-specific markers: skipping those was the
    /// "exclude password managers" rule the user asked to drop.
    private let concealedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType")
    ]
    private let transientTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type")
    ]

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        lastChangeCount = pasteboard.changeCount
        timer?.invalidate()
        let interval = UserDefaults.standard.double(forKey: "pollInterval")
        let polling = interval > 0 ? interval : 0.5
        let timer = Timer(timeInterval: polling, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.check() }
        }
        timer.tolerance = polling / 2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() { timer?.invalidate(); timer = nil }

    func ignoreNextWrite() {
        ignoredCounts.insert(pasteboard.changeCount + 1)
        if ignoredCounts.count > 20 { ignoredCounts.removeAll() }
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if ignoredCounts.remove(count) != nil { return }
        guard !isPaused else { return }
        // Coalesce clear+write sequences before materializing clipboard data.
        pendingCount = count
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) { [weak self] in
            // Only skip when a newer batch was already scheduled. If the source app
            // wrote again (e.g. file URL first, then icon preview) we still capture
            // the current content instead of dropping the clip entirely.
            guard let self, self.pendingCount == count else { return }
            self.pendingCount = nil
            self.capture()
        }
    }

    func captureNowForTesting() { capture() }

    private func capture() {
        guard let types = pasteboard.types, !concealedTypes.contains(where: types.contains) else {
            Diagnostics.log("capture.skipped", ["reason": "concealed"])
            return
        }
        let ignoreTransient = UserDefaults.standard.bool(forKey: "ignoreTransientItems")
        if ignoreTransient && transientTypes.contains(where: types.contains) { return }
        let isRemote = types.contains(.init("com.apple.is-remote-clipboard"))
        var app = NSWorkspace.shared.frontmostApplication
        if let declaredSource = pasteboard.string(forType: .init("org.nspasteboard.source")), !declaredSource.isEmpty {
            if let match = NSRunningApplication.runningApplications(withBundleIdentifier: declaredSource).first { app = match }
        }
        if let bundle = app?.bundleIdentifier, ignoredBundleIDs.contains(bundle) { return }
        if bundleIsOwnApp(app?.bundleIdentifier) { return }

        var fileURLs = readFileURLs(from: pasteboard, types: types)
        let text = readText()
        let imageTypes: [NSPasteboard.PasteboardType] = [
            .tiff, .png,
            // The NeXT/Apple spellings are distinct UTI strings, not aliases of
            // public.tiff / public.png; several apps write only these.
            .init("NeXT TIFF v4.0 pasteboard type"),
            .init("Apple PNG pasteboard type"),
            .init("public.jpeg"), .init("public.heic"), .init("public.webp"),
            .init("com.compuserve.gif"), .init("com.microsoft.bmp")
        ]
        let filesAreImages = fileURLs.isEmpty || fileURLs.allSatisfy {
            UTType(filenameExtension: $0.pathExtension)?.conforms(to: .image) == true
        }
        let declaresImage = filesAreImages && (imageTypes.contains(where: types.contains)
            || pasteboard.canReadItem(withDataConformingToTypes: [UTType.image.identifier]))
        var image = declaresImage ? NSImage(pasteboard: pasteboard) : nil
        var imageSource = "none"
        if image != nil { imageSource = "flavour" }
        if image == nil && declaresImage {
            for type in imageTypes {
                if let data = pasteboard.data(forType: type), let fallback = NSImage(data: data) {
                    image = fallback; imageSource = "flavour-\(type.rawValue)"; break
                }
            }
        }
        // Some screenshot tools put only a temporary PNG file URL on the pasteboard.
        if image == nil, filesAreImages, let url = fileURLs.first(where: isReadableImageFile) {
            image = loadImage(at: url)
            if image != nil { imageSource = "fileurl" }
        }
        // PixPin's Qt pasteboard may expose the image only through a private MIME blob.
        if image == nil, let found = scanPasteboardForEmbeddedImage(types: types) {
            image = found; imageSource = "scan"
        }
        // Browsers put no standalone image flavour on the board: the picture
        // lives in the RTF payload (as a hex blob), in the web archive, or in
        // the HTML as a file:// / data: / relative URL. Try all of them.
        if image == nil, let found = imageFromRTF() { image = found; imageSource = "rtf" }
        if image == nil, let found = imageFromWebArchive() { image = found; imageSource = "webarchive" }
        if image == nil, let found = imageFromHTML() { image = found; imageSource = "html" }
        // Last resort for PixPin's "copy image as file": use the just-created Temp image.
        let isPixPin = types.contains(.init("com.trolltech.anymime.PixPinData"))
            || app?.bundleIdentifier == "com.depthpicture.PixPin"
        if image == nil, isPixPin, let recent = newestPixPinTemporaryImage() {
            image = NSImage(contentsOf: recent)
            if image != nil && !fileURLs.contains(recent) { fileURLs.append(recent) }
        }
        guard !text.isEmpty || image != nil || !fileURLs.isEmpty else { return }
        if text.utf8.count > 2_000_000 { return }
        // Copied files take priority over Finder's icon/preview image data, so that
        // pasting gives back the original file instead of a rendered TIFF.
        // Exception: screenshot apps that copy through a temp image file (e.g. PixPin)
        // are still treated as image clips, because those temp files are short-lived.
        let isScreenshotTool = types.contains(.init("com.trolltech.anymime.PixPinData"))
            || app?.bundleIdentifier == "com.depthpicture.PixPin"
        let onlyImageFiles = !fileURLs.isEmpty && fileURLs.allSatisfy { isReadableImageFile($0) }
        let looksTemporary = fileURLs.contains { url in
            let path = url.path.lowercased()
            // macOS per-app temp dirs live under /var/folders/**/T/ ; /tmp and
            // /TemporaryItems are the other scratch locations.
            return path.contains("/var/folders/") || path.contains("/tmp/")
                || path.contains("/temp/") || path.contains("/temporaryitems/")
                || path.contains("screenshot") || path.contains("screen shot")
        }
        let kind: ClipKind
        if !fileURLs.isEmpty {
            kind = (isScreenshotTool || looksTemporary) && onlyImageFiles ? .image : .files
        } else if image != nil {
            kind = .image
        } else {
            kind = ClipClassifier.classify(text, hasImage: false, hasFiles: false)
        }
        // `text` is always the real text, never a generated stand-in. A copy can
        // carry a picture, text and files at once and all of it has to survive;
        // a picture-only clip simply has no text and is described by imageSize.
        let contentText: String
        if kind == .files {
            contentText = fileURLs.map(\.lastPathComponent).joined(separator: "\n")
        } else if !text.isEmpty {
            contentText = text
        } else {
            contentText = ""
        }
        // Order of the two halves, read from the HTML document order.
        var textFirst = false
        if kind == .image, !contentText.isEmpty {
            if let html = htmlPayload() {
                textFirst = textPrecedesImage(in: html, text: contentText)
            }
        }
        let item = ClipItem(
            kind: kind,
            text: contentText,
            sourceBundleID: app?.bundleIdentifier,
            sourceName: isRemote ? L("接力剪贴板", "Universal Clipboard") : app?.localizedName,
            sourcePath: app?.bundleURL?.path,
            isRemote: isRemote,
            filePaths: fileURLs.isEmpty ? nil : fileURLs.map(\.path),
            imageSize: image.map { "\(Int($0.size.width))×\(Int($0.size.height))" },
            textFirst: textFirst
        )
        onSound?()
        // Browser image+text copies carry only an <img> URL — no image data.
        // Fetch it in the background (never on the main thread) and update the
        // card in place when it lands.
        if image == nil, item.kind != .files,
           UserDefaults.standard.object(forKey: "fetchRemoteImages") as? Bool ?? true {
            let candidates = remoteImageURLs(types: types)
            if candidates.isEmpty {
                // Useful signal: the copy is text-only and the HTML carries no
                // reachable image URL (or no HTML at all).
                let hasHTML = types.contains(.init("public.html"))
                Diagnostics.log("image.fetch.none", ["hasHTML": String(hasHTML),
                                                     "types": types.prefix(6).map(\.rawValue).joined(separator: ",")])
            }
            if !candidates.isEmpty {
                let capturedID = item.id
                Diagnostics.log("image.fetch.try", [
                    "count": String(candidates.count),
                    "first": String(candidates[0].absoluteString.prefix(140))
                ])
                DispatchQueue.global(qos: .utility).async { [weak self] in
                    for url in candidates.prefix(3) {
                        if let fetched = Self.fetchImageSync(url) {
                            Diagnostics.log("image.fetch", ["url": String(url.absoluteString.prefix(140))])
                            DispatchQueue.main.async { [weak self] in
                                self?.onRemoteImage?(capturedID, fetched)
                            }
                            return
                        }
                        Diagnostics.log("image.fetch.fail", ["url": String(url.absoluteString.prefix(140))])
                    }
                }
            }
        }
        Diagnostics.log("capture.done", [
            "kind": kind.rawValue,
            "hasText": String(item.captionText != nil),
            "hasImage": String(image != nil),
            "imageFrom": imageSource,
            "fileCount": String(fileURLs.count),
            "imageSize": item.imageSize ?? "-"
        ])
        // Hand over the picture whenever there is one. Finder puts an icon
        // preview on the board for a file copy, and that is not the content,
        // so plain file clips still pass nil.
        onCapture?(item, kind == .files ? nil : image, htmlPayload()?.data(using: .utf8))
    }

    private func bundleIsOwnApp(_ bundle: String?) -> Bool {
        bundle != nil && bundle == Bundle.main.bundleIdentifier
    }

    /// Reads the clipboard's text without trusting AppKit's flavour mapping.
    ///
    /// Three traps, all verified against raw bytes or real mojibake in the log:
    /// 1. When an app publishes UTF-16 text, the system *derives* a
    ///    `public.utf8-plain-text` whose bytes are already mangled, so reading
    ///    `.string` yields mojibake.
    /// 2. Despite its name, `public.utf16-external-plain-text` frequently holds
    ///    **UTF-8** data.
    /// 3. `String(data:encoding:.utf16)` assumes **big-endian** when there is no
    ///    BOM, but apps write little-endian — decoding WeChat's caption that way
    ///    produced "⺕㥥饑齓…" in the history.
    ///
    /// The discriminator is structural: UTF-8 never contains 0x00 bytes, while
    /// UTF-16 text almost always does (every ASCII char has a zero half). So the
    /// byte order is decided per payload, not per flavour.
    private func readText() -> String {
        let prioritized: [NSPasteboard.PasteboardType] = [
            .init("public.utf16-external-plain-text"),
            .init("public.utf16-plain-text"),
            .string,
            .init("NSStringPboardType")
        ]
        var fallback = ""
        for type in prioritized {
            guard let data = pasteboard.data(forType: type) else { continue }
            guard let value = decodeText(data) else { continue }
            let cleaned = value.trimmingCharacters(in: .controlCharacters)
            guard !cleaned.isEmpty else { continue }
            if value.contains("\u{FFFD}") {
                if fallback.isEmpty { fallback = cleaned }
                continue
            }
            return cleaned
        }
        return fallback.isEmpty ? (pasteboard.string(forType: .string) ?? "") : fallback
    }

    /// Decodes clipboard text bytes, choosing UTF-8 vs UTF-16 (with the correct
    /// byte order) from the payload itself.
    private func decodeText(_ data: Data) -> String? {
        // Honour a byte order mark if there is one.
        if data.count >= 2 {
            let b0 = data[data.startIndex], b1 = data[data.index(after: data.startIndex)]
            if b0 == 0xFF && b1 == 0xFE { return String(data: data, encoding: .utf16LittleEndian) }
            if b0 == 0xFE && b1 == 0xFF { return String(data: data, encoding: .utf16BigEndian) }
        }
        // UTF-8 never contains 0x00; UTF-16 text with any Latin/ASCII content
        // always does. Zero bytes therefore mean "this is UTF-16".
        let hasZero = data.contains(0)
        if !hasZero, let value = String(data: data, encoding: .utf8), !value.isEmpty {
            return value
        }
        if hasZero {
            // Count zeros per half to pick the byte order: for LE, ASCII chars
            // put the zero second (odd index).
            var evenZeros = 0, oddZeros = 0
            for (offset, byte) in data.enumerated() where byte == 0 {
                if offset % 2 == 0 { evenZeros += 1 } else { oddZeros += 1 }
            }
            let order: String.Encoding = oddZeros >= evenZeros ? .utf16LittleEndian : .utf16BigEndian
            if let value = String(data: data, encoding: order), !value.isEmpty { return value }
            let other: String.Encoding = order == .utf16LittleEndian ? .utf16BigEndian : .utf16LittleEndian
            if let value = String(data: data, encoding: other), !value.isEmpty { return value }
            return nil
        }
        return String(data: data, encoding: .utf8)
    }

    private func readFileURLs(from pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> [URL] {
        var urls: [URL] = []
        if let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) {
            for object in objects {
                if let url = object as? URL, url.isFileURL { urls.append(url) }
                else if let url = object as? NSURL, url.isFileURL { urls.append(url as URL) }
            }
        }
        let pathTypes: [NSPasteboard.PasteboardType] = [
            .fileURL, .URL,
            .init("com.apple.pasteboard.promised-file-url"),
            .init("text/uri-list"),
            .init("NSFilenamesPboardType")
        ]
        for type in pathTypes {
            if let value = pasteboard.string(forType: type) {
                for candidate in value.components(separatedBy: .newlines) {
                    if let url = parseFileURL(candidate) { urls.append(url) }
                }
            }
            if let values = pasteboard.propertyList(forType: type) as? [String] {
                for value in values { if let url = parseFileURL(value) { urls.append(url) } }
            }
        }
        // Qt-based apps sometimes encode the path inside a private MIME blob.
        for type in types where type.rawValue.hasPrefix("com.trolltech.") {
            if let data = pasteboard.data(forType: type), data.count < 2_000_000,
               let value = String(data: data, encoding: .utf8) {
                for match in imagePaths(in: value) where !urls.contains(match) { urls.append(match) }
            }
        }
        var seen = Set<String>()
        return urls.filter { seen.insert($0.standardizedFileURL.path).inserted }
    }

    private func imagePaths(in text: String) -> [URL] {
        let pattern = #"(?:file://)?(/[^\x00\n\r\t"'<>]+?\.(?:png|jpe?g|tiff?|heic|webp|gif|bmp))"#
        guard let regex = try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive]) else { return [] }
        let range = NSRange(text.startIndex..<text.endIndex, in: text)
        return regex.matches(in: text, range: range).compactMap { match in
            guard let pathRange = Range(match.range(at: 1), in: text) else { return nil }
            let path = String(text[pathRange]).removingPercentEncoding ?? String(text[pathRange])
            let url = URL(fileURLWithPath: path)
            return FileManager.default.fileExists(atPath: url.path) ? url : nil
        }
    }

    /// Accepts any file URL / absolute path, not just images. Some apps only expose
    /// the file path as a plain string, and filtering to images would drop them.
    private func parseFileURL(_ value: String) -> URL? {
        let clean = value.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !clean.isEmpty else { return nil }
        var url: URL
        if clean.lowercased().hasPrefix("file://") {
            guard let parsed = URL(string: clean), parsed.isFileURL else { return nil }
            url = parsed
        } else if clean.hasPrefix("/") {
            url = URL(fileURLWithPath: clean)
        } else {
            return nil
        }
        // A promised file (iCloud / cloud drive) may not be downloaded yet: keep the
        // path even when the file is not on disk, so the clip is still recorded.
        if isReadableImageFile(url) { return url }
        var isDirectory: ObjCBool = false
        if FileManager.default.fileExists(atPath: url.path, isDirectory: &isDirectory) { return url }
        if url.pathExtension.isEmpty { return nil }
        return url
    }

    private func isReadableImageFile(_ url: URL) -> Bool {
        guard url.isFileURL,
              UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true,
              let values = try? url.resourceValues(forKeys: [.fileSizeKey, .isRegularFileKey]),
              values.isRegularFile == true, (values.fileSize ?? 0) <= 12_000_000 else { return false }
        return true
    }

    private func loadImage(at url: URL) -> NSImage? {
        guard isReadableImageFile(url), let data = try? Data(contentsOf: url, options: .mappedIfSafe) else { return nil }
        return NSImage(data: data)
    }

    private func scanPasteboardForEmbeddedImage(types: [NSPasteboard.PasteboardType]) -> NSImage? {
        let skip: Set<String> = [
            "public.utf8-plain-text", "public.utf16-plain-text", "public.html", "public.rtf",
            "public.file-url", "NSStringPboardType", "NSFilenamesPboardType"
        ]
        for type in types where !skip.contains(type.rawValue) {
            guard let data = pasteboard.data(forType: type), data.count > 16, data.count <= 16_000_000 else { continue }
            if let image = NSImage(data: data) { return image }
            // Some wrappers prepend metadata. Locate common image signatures within the blob.
            let signatures: [[UInt8]] = [
                [0x89, 0x50, 0x4E, 0x47], // PNG
                [0xFF, 0xD8, 0xFF],       // JPEG
                [0x49, 0x49, 0x2A, 0x00], // TIFF little endian
                [0x4D, 0x4D, 0x00, 0x2A]  // TIFF big endian
            ]
            for signature in signatures {
                if let range = data.range(of: Data(signature)), range.lowerBound < data.count - 32 {
                    let candidate = data.subdata(in: range.lowerBound..<data.count)
                    if let image = NSImage(data: candidate) { return image }
                }
            }
        }
        return nil
    }

    /// Pulls an embedded image out of an RTF payload.
    ///
    /// Word, TextEdit and several note apps put the picture on the board as a
    /// hex blob inside the RTF (`{\*\shppict{\pict\pngblip <hex>}}`) with no
    /// separate image flavour, so without this an image+text copy came through
    /// as text only.
    private func imageFromRTF() -> NSImage? {
        for type in [NSPasteboard.PasteboardType("public.rtf"),
                     NSPasteboard.PasteboardType("NeXT Rich Text Format v1.0 pasteboard type"),
                     NSPasteboard.PasteboardType("com.apple.flat-rtfd"),
                     NSPasteboard.PasteboardType("NeXT RTFD pasteboard type")] {
            guard let data = pasteboard.data(forType: type), !data.isEmpty else { continue }
            // The hex blob is ASCII inside an otherwise binary container, so a
            // lossy decode still exposes the hex digits we need.
            guard let raw = String(data: data, encoding: .windowsCP1252) ?? String(data: data, encoding: .ascii) else { continue }
            let markers = ["pngblip", "jpegblip", "blip"]
            for marker in markers {
                if let range = raw.range(of: marker) {
                    // Skip past the marker and any whitespace / control words.
                    var index = raw.index(range.upperBound, offsetBy: 0)
                    while index < raw.endIndex, raw[index].isWhitespace || raw[index] == "\r" || raw[index] == "\n" {
                        index = raw.index(after: index)
                    }
                    var hex = ""
                    while index < raw.endIndex, "0123456789abcdefABCDEF".contains(raw[index]) {
                        hex.append(raw[index])
                        index = raw.index(after: index)
                    }
                    if hex.count > 64, let bytes = Data(hexString: hex), let image = NSImage(data: bytes) {
                        return image
                    }
                }
            }
        }
        return nil
    }

    /// Pulls an image out of a Safari/WebKit web archive.
    ///
    /// `com.apple.webarchive` is a property list whose subresources carry the
    /// picture as base64 in `WebResourceData`.
    private func imageFromWebArchive() -> NSImage? {
        for type in [NSPasteboard.PasteboardType("com.apple.webarchive"),
                     NSPasteboard.PasteboardType("Apple Web Archive pasteboard type")] {
            guard let data = pasteboard.data(forType: type),
                  let plist = try? PropertyListSerialization.propertyList(from: data, format: nil),
                  let root = plist as? [String: Any] else { continue }
            let subresources = (root["WebSubresources"] as? [[String: Any]]) ?? []
            for resource in subresources {
                guard let mime = resource["WebResourceMIMEType"] as? String,
                      mime.hasPrefix("image/"),
                      let payload = resource["WebResourceData"] as? Data,
                      let image = NSImage(data: payload) else { continue }
                return image
            }
        }
        return nil
    }

    /// Pulls an image out of an HTML payload.
    ///
    /// Copying a selection from a browser usually puts `public.html` on the board
    /// with the picture referenced by a local `file://` URL, plus the plain text.
    /// `scanPasteboardForEmbeddedImage` deliberately skips HTML (it is text), so
    /// without this the clip arrived as text only.
    private func imageFromHTML() -> NSImage? {
        guard let data = pasteboard.data(forType: .init("public.html")),
              let html = String(data: data, encoding: .utf8) else { return nil }
        let pattern = "<img[^>]+src\\s*=\\s*[\"']([^\"']+)[\"']"
        guard let regex = try? NSRegularExpression(pattern: pattern, options: .caseInsensitive) else { return nil }
        let matches = regex.matches(in: html, options: [], range: NSRange(html.startIndex..., in: html))
        guard !matches.isEmpty else { return nil }
        // Try every image in document order (bounded): the first one can be a
        // tracking pixel that decodes to a useless 1×1.
        for match in matches.prefix(4) {
            guard let srcRange = Range(match.range(at: 1), in: html) else { continue }
            let src = String(html[srcRange])
            if let image = loadImage(fromHTMLSource: src) { return image }
        }
        return nil
    }

    /// Resolves one `<img src>` value to an image.
    private func loadImage(fromHTMLSource src: String) -> NSImage? {

        // A base64 data: URI carries the picture inline — no file, no network.
        if src.hasPrefix("data:") {
            let comma = src.firstIndex(of: ",") ?? src.endIndex
            let meta = src[src.startIndex..<comma]
            let payload = src[src.index(after: comma)...]
            guard meta.contains("base64"), let bytes = Data(base64Encoded: String(payload)) else { return nil }
            return NSImage(data: bytes)
        }
        // A local file URL is readable directly.
        if src.hasPrefix("file://"), let url = URL(string: src) {
            return NSImage(contentsOf: url)
        }
        // A relative path is resolved against the page the copy came from, when
        // that page is itself local.
        if !src.contains("://"), src.hasPrefix("/") == false {
            if let pageURL = pasteboard.string(forType: .init("org.chromium.source-url")),
               let base = URL(string: pageURL), base.scheme == "file",
               let resolved = URL(string: src, relativeTo: base)?.absoluteURL {
                return NSImage(contentsOf: resolved)
            }
        }
        return nil
    }

    /// The raw HTML payload, when the source put one on the board.
    private func htmlPayload() -> String? {
        for type in [NSPasteboard.PasteboardType("public.html"),
                     NSPasteboard.PasteboardType("Apple HTML pasteboard type")] {
            if let data = pasteboard.data(forType: type),
               let html = String(data: data, encoding: .utf8), !html.isEmpty {
                return html
            }
        }
        return nil
    }

    /// True when the caption sits before the picture in the markup.
    ///
    /// The check locates the *actual* text in the document rather than merely
    /// asking whether any text precedes the image: a browser fragment often
    /// starts with a `<meta>`/`<span>` wrapper, so "is there visible text
    /// before `<img`" can be true for whitespace alone.
    private func textPrecedesImage(in html: String, text: String) -> Bool {
        guard let imgIndex = html.range(of: "<img", options: .caseInsensitive)?.lowerBound else {
            // No picture in the markup: the text is the whole content.
            return true
        }
        let probe = String(text.prefix(24)).trimmingCharacters(in: .whitespacesAndNewlines)
        if !probe.isEmpty, let textRange = html.range(of: probe) {
            return textRange.lowerBound < imgIndex
        }
        let head = String(html[html.startIndex..<imgIndex])
        let stripped = head.replacingOccurrences(of: "<[^>]+>", with: " ",
                                                 options: .regularExpression)
        return stripped.rangeOfCharacter(from: CharacterSet.whitespacesAndNewlines.inverted) != nil
    }

    /// Remote image URLs from the HTML payload, in document order.
    ///
    /// Browsers do not agree on how the picture is referenced — plain `src`,
    /// lazy-loaded `data-src`, `srcset` descriptors, or a CSS background — so
    /// every common form is collected.
    private func remoteImageURLs(types: [NSPasteboard.PasteboardType]) -> [URL] {
        let patterns = [
            "<img[^>]+\\ssrc\\s*=\\s*[\"']([^\"']+)[\"']",
            "<img[^>]+data-src\\s*=\\s*[\"']([^\"']+)[\"']",
            "<img[^>]+srcset\\s*=\\s*[\"']([^\"'\\s,]+)",
            "background-image\\s*:\\s*url\\(\\s*[\"']?([^\"')]+)"
        ]
        for type in [NSPasteboard.PasteboardType("public.html"),
                     NSPasteboard.PasteboardType("Apple HTML pasteboard type")] {
            guard let data = pasteboard.data(forType: type),
                  let html = String(data: data, encoding: .utf8) else { continue }
            var urls: [URL] = []
            var seen = Set<String>()
            for pattern in patterns {
                guard let regex = try? NSRegularExpression(pattern: pattern, options: .caseInsensitive) else { continue }
                let matches = regex.matches(in: html, options: [], range: NSRange(html.startIndex..., in: html))
                for match in matches.prefix(6) {
                    guard match.numberOfRanges > 1,
                          let range = Range(match.range(at: 1), in: html) else { continue }
                    let src = String(html[range])
                    guard src.hasPrefix("http://") || src.hasPrefix("https://"),
                          seen.insert(src).inserted,
                          let url = URL(string: src) else { continue }
                    urls.append(url)
                }
            }
            if !urls.isEmpty { return urls }
        }
        return []
    }

    /// Blocking fetch, safe to call off the main thread. Loopback URLs bypass
    /// the system proxy, which on some setups intercepts even localhost.
    static func fetchImageSync(_ url: URL) -> NSImage? {
        let semaphore = DispatchSemaphore(value: 0)
        var result: NSImage?
        var request = URLRequest(url: url)
        request.timeoutInterval = 8
        let config = URLSessionConfiguration.default
        if let host = url.host, host == "127.0.0.1" || host == "localhost" {
            config.connectionProxyDictionary = [:]
        }
        let session = URLSession(configuration: config)
        let task = session.dataTask(with: request) { data, response, _ in
            defer {
                semaphore.signal()
                session.finishTasksAndInvalidate()
            }
            guard let http = response as? HTTPURLResponse, (200..<300).contains(http.statusCode),
                  let data, data.count <= 24_000_000, data.count > 64,
                  let image = NSImage(data: data) else { return }
            result = image
        }
        task.resume()
        _ = semaphore.wait(timeout: .now() + 10)
        return result
    }

    private func newestPixPinTemporaryImage() -> URL? {
        let directory = URL(fileURLWithPath: NSHomeDirectory())
            .appendingPathComponent("Library/Application Support/PixPin/Temp", isDirectory: true)
        guard let files = try? FileManager.default.contentsOfDirectory(
            at: directory,
            includingPropertiesForKeys: [.contentModificationDateKey, .fileSizeKey, .isRegularFileKey],
            options: [.skipsHiddenFiles]
        ) else { return nil }
        let now = Date()
        return files.filter { url in
            guard UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true,
                  let values = try? url.resourceValues(forKeys: [.contentModificationDateKey, .fileSizeKey, .isRegularFileKey]),
                  values.isRegularFile == true, (values.fileSize ?? 0) <= 12_000_000,
                  let date = values.contentModificationDate,
                  abs(date.timeIntervalSince(now)) < 30 else { return false }
            return true
        }.max { lhs, rhs in
            let l = (try? lhs.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate) ?? .distantPast
            let r = (try? rhs.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate) ?? .distantPast
            return l < r
        }
    }
}

extension Data {
    /// Builds `Data` from a hex string, ignoring anything that is not a hex digit.
    init?(hexString: String) {
        let digits = hexString.filter { "0123456789abcdefABCDEF".contains($0) }
        guard digits.count % 2 == 0, !digits.isEmpty else { return nil }
        var bytes = [UInt8]()
        bytes.reserveCapacity(digits.count / 2)
        var index = digits.startIndex
        while index < digits.endIndex {
            let next = digits.index(after: index)
            guard let byte = UInt8(digits[index...next], radix: 16) else { return nil }
            bytes.append(byte)
            index = digits.index(after: next)
        }
        self = Data(bytes)
    }
}
