import AppKit
import Foundation
import UniformTypeIdentifiers

@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published var isPaused = false
    var onCapture: ((ClipItem, NSImage?) -> Void)?
    var onSound: (() -> Void)?
    @Published var ignoredBundleIDs: Set<String> = ["com.agilebits.onepassword", "com.1password.1password", "net.antelle.keeweb"]
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChangeCount = 0
    private var pendingCount: Int?
    private var ignoredCounts: Set<Int> = []
    private let concealedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("com.agilebits.onepassword"),
        .init("net.antelle.keeweb")
    ]
    private let transientTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type")
    ]

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        lastChangeCount = pasteboard.changeCount
        timer?.invalidate()
        let interval = UserDefaults.standard.double(forKey: "pollInterval")
        let polling = interval > 0 ? interval : 0.5
        let timer = Timer(timeInterval: polling, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.check() }
        }
        timer.tolerance = polling / 2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() { timer?.invalidate(); timer = nil }

    func ignoreNextWrite() {
        ignoredCounts.insert(pasteboard.changeCount + 1)
        if ignoredCounts.count > 20 { ignoredCounts.removeAll() }
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if ignoredCounts.remove(count) != nil { return }
        guard !isPaused else { return }
        // Coalesce clear+write sequences before materializing clipboard data.
        pendingCount = count
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) { [weak self] in
            // Only skip when a newer batch was already scheduled. If the source app
            // wrote again (e.g. file URL first, then icon preview) we still capture
            // the current content instead of dropping the clip entirely.
            guard let self, self.pendingCount == count else { return }
            self.pendingCount = nil
            self.capture()
        }
    }

    func captureNowForTesting() { capture() }

    private func capture() {
        guard let types = pasteboard.types, !concealedTypes.contains(where: types.contains) else { return }
        let ignoreTransient = UserDefaults.standard.bool(forKey: "ignoreTransientItems")
        if ignoreTransient && transientTypes.contains(where: types.contains) { return }
        let isRemote = types.contains(.init("com.apple.is-remote-clipboard"))
        var app = NSWorkspace.shared.frontmostApplication
        if let declaredSource = pasteboard.string(forType: .init("org.nspasteboard.source")), !declaredSource.isEmpty {
            if let match = NSRunningApplication.runningApplications(withBundleIdentifier: declaredSource).first { app = match }
        }
        if let bundle = app?.bundleIdentifier, ignoredBundleIDs.contains(bundle) { return }
        if bundleIsOwnApp(app?.bundleIdentifier) { return }

        var fileURLs = readFileURLs(from: pasteboard, types: types)
        let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .controlCharacters) ?? ""
        let imageTypes: [NSPasteboard.PasteboardType] = [
            .tiff, .png, .init("public.jpeg"), .init("public.heic"), .init("public.webp"),
            .init("com.compuserve.gif"), .init("com.microsoft.bmp")
        ]
        let filesAreImages = fileURLs.isEmpty || fileURLs.allSatisfy {
            UTType(filenameExtension: $0.pathExtension)?.conforms(to: .image) == true
        }
        let declaresImage = filesAreImages && (imageTypes.contains(where: types.contains)
            || pasteboard.canReadItem(withDataConformingToTypes: [UTType.image.identifier]))
        var image = declaresImage ? NSImage(pasteboard: pasteboard) : nil
        if image == nil && declaresImage {
            for type in imageTypes {
                if let data = pasteboard.data(forType: type), let fallback = NSImage(data: data) { image = fallback; break }
            }
        }
        // Some screenshot tools put only a temporary PNG file URL on the pasteboard.
        if image == nil, filesAreImages, let url = fileURLs.first(where: isReadableImageFile) {
            image = loadImage(at: url)
        }
        // PixPin's Qt pasteboard may expose the image only through a private MIME blob.
        if image == nil {
            image = scanPasteboardForEmbeddedImage(types: types)
        }
        // Last resort for PixPin's "copy image as file": use the just-created Temp image.
        let isPixPin = types.contains(.init("com.trolltech.anymime.PixPinData"))
            || app?.bundleIdentifier == "com.depthpicture.PixPin"
        if image == nil, isPixPin, let recent = newestPixPinTemporaryImage() {
            image = NSImage(contentsOf: recent)
            if image != nil && !fileURLs.contains(recent) { fileURLs.append(recent) }
        }
        guard !text.isEmpty || image != nil || !fileURLs.isEmpty else { return }
        if text.utf8.count > 2_000_000 { return }
        // Copied files take priority over Finder's icon/preview image data, so that
        // pasting gives back the original file instead of a rendered TIFF.
        // Exception: screenshot apps that copy through a temp image file (e.g. PixPin)
        // are still treated as image clips, because those temp files are short-lived.
        let isScreenshotTool = types.contains(.init("com.trolltech.anymime.PixPinData"))
            || app?.bundleIdentifier == "com.depthpicture.PixPin"
        let onlyImageFiles = !fileURLs.isEmpty && fileURLs.allSatisfy { isReadableImageFile($0) }
        let looksTemporary = fileURLs.contains { url in
            let path = url.path.lowercased()
            // macOS per-app temp dirs live under /var/folders/**/T/ ; /tmp and
            // /TemporaryItems are the other scratch locations.
            return path.contains("/var/folders/") || path.contains("/tmp/")
                || path.contains("/temp/") || path.contains("/temporaryitems/")
                || path.contains("screenshot") || path.contains("screen shot")
        }
        let kind: ClipKind
        if !fileURLs.isEmpty {
            kind = (isScreenshotTool || looksTemporary) && onlyImageFiles ? .image : .files
        } else if image != nil {
            kind = .image
        } else {
            kind = ClipClassifier.classify(text, hasImage: false, hasFiles: false)
        }
        let imageDescription = image.map { "\(L("截图", "Screenshot")) · \(Int($0.size.width))×\(Int($0.size.height))" } ?? L("图片", "Image")
        let contentText: String
        if kind == .files {
            contentText = fileURLs.map(\.lastPathComponent).joined(separator: "\n")
        } else if kind == .image {
            contentText = imageDescription
        } else if !text.isEmpty {
            contentText = text
        } else {
            contentText = fileURLs.map(\.lastPathComponent).joined(separator: "\n")
        }
        let item = ClipItem(
            kind: kind,
            text: contentText,
            sourceBundleID: app?.bundleIdentifier,
            sourceName: isRemote ? L("接力剪贴板", "Universal Clipboard") : app?.localizedName,
            sourcePath: app?.bundleURL?.path,
            isRemote: isRemote,
            filePaths: fileURLs.isEmpty ? nil : fileURLs.map(\.path)
        )
        onSound?()
        onCapture?(item, kind == .files ? nil : image)
    }

    private func bundleIsOwnApp(_ bundle: String?) -> Bool {
        bundle != nil && bundle == Bundle.main.bundleIdentifier
    }

    private func readFileURLs(from pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> [URL] {
        var urls: [URL] = []
        if let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) {
            for object in objects {
                if let url = object as? URL, url.isFileURL { urls.append(url) }
                else if let url = object as? NSURL, url.isFileURL { urls.append(url as URL) }
            }
        }
        let pathTypes: [NSPasteboard.PasteboardType] = [
            .fileURL, .URL,
            .init("com.apple.pasteboard.promised-file-url"),
            .init("text/uri-list"),
            .init("NSFilenamesPboardType")
        ]
        for type in pathTypes {
            if let value = pasteboard.string(forType: type) {
                for candidate in value.components(separatedBy: .newlines) {
                    if let url = parseFileURL(candidate) { urls.append(url) }
                }
            }
            if let values = pasteboard.propertyList(forType: type) as? [String] {
                for value in values { if let url = parseFileURL(value) { urls.append(url) } }
            }
        }
        // Qt-based apps sometimes encode the path inside a private MIME blob.
        for type in types where type.rawValue.hasPrefix("com.trolltech.") {
            if let data = pasteboard.data(forType: type), data.count < 2_000_000,
               let value = String(data: data, encoding: .utf8) {
                for match in imagePaths(in: value) where !urls.contains(match) { urls.append(match) }
            }
        }
        var seen = Set<String>()
        return urls.filter { seen.insert($0.standardizedFileURL.path).inserted }
    }

    private func imagePaths(in text: String) -> [URL] {
        let pattern = #"(?:file://)?(/[^\x00\n\r\t"'<>]+?\.(?:png|jpe?g|tiff?|heic|webp|gif|bmp))"#
        guard let regex = try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive]) else { return [] }
        let range = NSRange(text.startIndex..<text.endIndex, in: text)
        return regex.matches(in: text, range: range).compactMap { match in
            guard let pathRange = Range(match.range(at: 1), in: text) else { return nil }
            let path = String(text[pathRange]).removingPercentEncoding ?? String(text[pathRange])
            let url = URL(fileURLWithPath: path)
            return FileManager.default.fileExists(atPath: url.path) ? url : nil
        }
    }

    /// Accepts any file URL / absolute path, not just images. Some apps only expose
    /// the file path as a plain string, and filtering to images would drop them.
    private func parseFileURL(_ value: String) -> URL? {
        let clean = value.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !clean.isEmpty else { return nil }
        var url: URL
        if clean.lowercased().hasPrefix("file://") {
            guard let parsed = URL(string: clean), parsed.isFileURL else { return nil }
            url = parsed
        } else if clean.hasPrefix("/") {
            url = URL(fileURLWithPath: clean)
        } else {
            return nil
        }
        // A promised file (iCloud / cloud drive) may not be downloaded yet: keep the
        // path even when the file is not on disk, so the clip is still recorded.
        if isReadableImageFile(url) { return url }
        var isDirectory: ObjCBool = false
        if FileManager.default.fileExists(atPath: url.path, isDirectory: &isDirectory) { return url }
        if url.pathExtension.isEmpty { return nil }
        return url
    }

    private func isReadableImageFile(_ url: URL) -> Bool {
        guard url.isFileURL,
              UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true,
              let values = try? url.resourceValues(forKeys: [.fileSizeKey, .isRegularFileKey]),
              values.isRegularFile == true, (values.fileSize ?? 0) <= 12_000_000 else { return false }
        return true
    }

    private func loadImage(at url: URL) -> NSImage? {
        guard isReadableImageFile(url), let data = try? Data(contentsOf: url, options: .mappedIfSafe) else { return nil }
        return NSImage(data: data)
    }

    private func scanPasteboardForEmbeddedImage(types: [NSPasteboard.PasteboardType]) -> NSImage? {
        let skip: Set<String> = [
            "public.utf8-plain-text", "public.utf16-plain-text", "public.html", "public.rtf",
            "public.file-url", "NSStringPboardType", "NSFilenamesPboardType"
        ]
        for type in types where !skip.contains(type.rawValue) {
            guard let data = pasteboard.data(forType: type), data.count > 16, data.count <= 16_000_000 else { continue }
            if let image = NSImage(data: data) { return image }
            // Some wrappers prepend metadata. Locate common image signatures within the blob.
            let signatures: [[UInt8]] = [
                [0x89, 0x50, 0x4E, 0x47], // PNG
                [0xFF, 0xD8, 0xFF],       // JPEG
                [0x49, 0x49, 0x2A, 0x00], // TIFF little endian
                [0x4D, 0x4D, 0x00, 0x2A]  // TIFF big endian
            ]
            for signature in signatures {
                if let range = data.range(of: Data(signature)), range.lowerBound < data.count - 32 {
                    let candidate = data.subdata(in: range.lowerBound..<data.count)
                    if let image = NSImage(data: candidate) { return image }
                }
            }
        }
        return nil
    }

    private func newestPixPinTemporaryImage() -> URL? {
        let directory = URL(fileURLWithPath: NSHomeDirectory())
            .appendingPathComponent("Library/Application Support/PixPin/Temp", isDirectory: true)
        guard let files = try? FileManager.default.contentsOfDirectory(
            at: directory,
            includingPropertiesForKeys: [.contentModificationDateKey, .fileSizeKey, .isRegularFileKey],
            options: [.skipsHiddenFiles]
        ) else { return nil }
        let now = Date()
        return files.filter { url in
            guard UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true,
                  let values = try? url.resourceValues(forKeys: [.contentModificationDateKey, .fileSizeKey, .isRegularFileKey]),
                  values.isRegularFile == true, (values.fileSize ?? 0) <= 12_000_000,
                  let date = values.contentModificationDate,
                  abs(date.timeIntervalSince(now)) < 30 else { return false }
            return true
        }.max { lhs, rhs in
            let l = (try? lhs.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate) ?? .distantPast
            let r = (try? rhs.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate) ?? .distantPast
            return l < r
        }
    }
}
